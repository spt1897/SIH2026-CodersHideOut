import socket

def get_server_ip():
    """
       Returns the dynamic IP Address of the server which it is using over network
    """
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        return "127.0.0.1" #incase we are offline